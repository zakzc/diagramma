"""Dependency graph (SPEC §9.3): a layered `flowchart TB` built from import statements only.

Plain top-down layout: importers above, what they import below, one colour per layer and the
layer number on every box. Edges are the transitively reduced forward imports; imports against
the layer order (the cycle structure) are not drawn but counted on their endpoints and listed
in the summary. Deterministic.
"""

from dataclasses import dataclass

from app.analysis.layering import MAX_SPAN, Layering, layer_graph
from app.errors import AppError
from app.models import LayersSummary, Model, UpwardEdge
from app.render.c4 import RenderMeta
from app.render.escape import label
from app.render.flowchart import _width
from app.render.view import build_view

# One soft colour per layer, cycling; layer 0 (foundations) first.
LAYER_FILLS = [
    "#DDF3E4",
    "#E6F0FF",
    "#FFF1CC",
    "#FBE0E0",
    "#EADFF7",
    "#D9F2F2",
    "#FDE2C4",
    "#E6E8EB",
]
TOP_UPWARD = 10


@dataclass
class LayerAnalysis:
    layering: Layering
    names: dict[str, str]  # node id -> display name
    containers: dict[str, str]  # node id -> container name
    externals: set[str]
    summary: LayersSummary


def analyze_layers(model: Model, depth: int, max_span: int = MAX_SPAN) -> LayerAnalysis:
    """Layer the import graph of the boxes visible at `depth` plus the externals imports reach."""
    if model.relations and not any(r.evidence for r in model.relations):
        raise AppError(
            "LAYERS_UNAVAILABLE",
            "This diagram was generated before the dependency graph existed. "
            "Submit the repository again to regenerate it.",
        )
    view = build_view(model, depth)
    names: dict[str, str] = {}
    containers: dict[str, str] = {}
    boxes: set[str] = set()

    def walk(n, cname: str) -> None:
        for c in n.children:
            walk(c, cname)
        if not n.children:
            boxes.add(n.comp.id)
            names[n.comp.id] = n.comp.name
            containers[n.comp.id] = cname

    for c, roots in view.containers:
        for r in roots:
            walk(r, c.name)
    externals = {e.id for e in model.externals}
    for e in model.externals:
        names[e.id] = e.name
    known = boxes | externals

    edges = {
        (r.source, r.target): r.strength
        for r in view.relations
        if "import" in r.evidence and r.source in known and r.target in known
    }
    nodes = sorted({x for e in edges for x in e})
    lay = layer_graph(nodes, edges, max_span)
    isolated = len(boxes - set(nodes))
    top = sorted(lay.upward.items(), key=lambda kv: (-kv[1], kv[0]))[:TOP_UPWARD]
    summary = LayersSummary(
        layer_count=lay.layer_count,
        layer_sizes=lay.layer_sizes(),
        nodes=len(nodes),
        edges_drawn=len(lay.drawn),
        edges_transitive_omitted=lay.transitive_omitted,
        edges_long_omitted=lay.long_omitted,
        max_span=max_span,
        upward_edges=len(lay.upward),
        longest_chain=lay.layer_count,
        isolated=isolated,
        top_upward=[UpwardEdge(source=names[s], target=names[t], strength=w) for (s, t), w in top],
    )
    return LayerAnalysis(lay, names, containers, externals, summary)


def render_layers(
    model: Model, meta: RenderMeta, depth: int, analysis: LayerAnalysis | None = None
) -> str:
    a = analysis or analyze_layers(model, depth)
    lay, s = a.layering, a.summary
    multi = len(set(a.containers.values())) > 1
    up_count: dict[str, int] = {}
    for src, dst in lay.upward:
        up_count[src] = up_count.get(src, 0) + 1
        up_count[dst] = up_count.get(dst, 0) + 1

    lines = [
        "flowchart TB",
        f"    %% Generated by Diagramma {meta.tool_version} - dependency graph",
        f"    %% repo: {meta.repo} | ref: {meta.ref or 'HEAD'} | depth: {depth}",
        f"    %% commit: {meta.commit} | {meta.commit_date}",
        f"    %% {s.layer_count} layers, {s.nodes} nodes, {s.edges_drawn} edges drawn; omitted: "
        f"{s.edges_transitive_omitted} implied by another path, {s.edges_long_omitted} spanning "
        f"more than {s.max_span} layers; {s.upward_edges} upward (not drawn); "
        f"{s.isolated} isolated",
    ]
    for i, fill in enumerate(LAYER_FILLS):
        lines.append(f"    classDef lay{i} fill:{fill},stroke:#6B7280,color:#111827")
    lines.append("    classDef ext fill:#C7E3F7,stroke:#2F7FB5,color:#111827")
    lines.append("    classDef cyc stroke:#D33,stroke-width:3px,stroke-dasharray:5 3")
    lines.append("")

    if not lay.layer:
        lines.append('    none["No import relations at this depth"]')
        return "\n".join(lines) + "\n"

    by_class: dict[str, list[str]] = {}
    for n in sorted(lay.layer, key=lambda x: (-lay.layer[x], x)):  # top layer first
        parts = [label(a.names[n])]
        if multi and n in a.containers:
            parts.append(f"[{label(a.containers[n])}]")
        if n in a.externals:
            lines.append(f'    {n}[("{"<br/>".join(parts)}")]')
            by_class.setdefault("ext", []).append(n)
            continue
        parts.append(f"L{lay.layer[n]}" + (f" · ↑{up_count[n]}" if n in up_count else ""))
        lines.append(f'    {n}["{"<br/>".join(parts)}"]')
        by_class.setdefault(f"lay{lay.layer[n] % len(LAYER_FILLS)}", []).append(n)
        if n in up_count:
            by_class.setdefault("cyc", []).append(n)

    lines.append("")
    link_styles: list[str] = []
    for i, ((src, dst), w) in enumerate(sorted(lay.drawn.items())):
        lines.append(f'    {src} -->|"×{w}"| {dst}' if w > 1 else f"    {src} --> {dst}")
        if (width := _width(w)) is not None:
            link_styles.append(f"    linkStyle {i} stroke-width:{width}px")
    lines.append("")
    for cls in [*(f"lay{i}" for i in range(len(LAYER_FILLS))), "ext", "cyc"]:
        if cls in by_class:
            lines.append(f"    class {','.join(by_class[cls])} {cls}")
    lines += link_styles
    return "\n".join(lines) + "\n"

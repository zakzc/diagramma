"""Native Mermaid C4 output (SPEC §9.1). Deterministic: no clock, stable ordering."""

from dataclasses import dataclass

from app.models import Component, Container, External, Model
from app.render.escape import label
from app.render.view import ViewNode, auto_depth, build_view


@dataclass(frozen=True)
class RenderMeta:
    repo: str
    ref: str | None
    commit: str
    commit_date: str
    tool_version: str


def _args(*parts: str | None) -> str:
    return ", ".join(f'"{label(p)}"' for p in parts if p)


def _external(e: External, indent: str) -> str:
    fn = {"database": "ContainerDb", "queue": "ContainerQueue", "system": "System_Ext"}[e.kind]
    return f"{indent}{fn}({e.id}, {_args(e.name, e.technology)})"


def _component(c: Component, indent: str) -> str:
    fn = "ComponentDb" if c.role == "repository" else "Component"
    return f"{indent}{fn}({c.id}, {_args(c.name, c.technology, c.description)})"


def header(meta: RenderMeta, depth: int, comment: str = "%%") -> list[str]:
    return [
        f"    {comment} Generated by Diagramma {meta.tool_version}",
        f"    {comment} repo: {meta.repo} | ref: {meta.ref or 'HEAD'} | depth: {depth}",
        f"    {comment} commit: {meta.commit} | {meta.commit_date}",
    ]


def _node(n: ViewNode, indent: str, out: list[str]) -> None:
    if n.children:  # a folder group, drawn as a nested boundary
        k = n.comp
        out.append(f"{indent}Boundary({k.id}, {_args(k.name, f'{k.file_count} files')}) {{")
        for ch in n.children:
            _node(ch, indent + "    ", out)
        out.append(f"{indent}}}")
    else:
        out.append(_component(n.comp, indent))


def render_c4(model: Model, meta: RenderMeta, depth: int | None = None) -> str:
    """`C4Component` with a Container_Boundary per container and nested boundaries for folders.

    Falls back to `C4Container` when no container has components (e.g. only compose services).
    Mermaid's C4 layout copes poorly with deep nesting; the flowchart is the better deep view.
    """
    depth = depth or auto_depth(model)
    view = build_view(model, depth)
    has_components = any(roots for _, roots in view.containers)
    kind = "Component" if has_components else "Container"
    lines = [
        f"C4{kind}",
        *header(meta, depth),
        f"    title {kind} diagram for {label(model.system_name)}",
        "",
    ]

    for c, roots in view.containers:
        if roots:
            lines.append(f"    Container_Boundary({c.id}, {_args(c.name, c.technology)}) {{")
            for n in roots:
                _node(n, "        ", lines)
            lines.append("    }")
        else:  # no source files of its own (e.g. an infrastructure-only compose service)
            lines.append(f"    Container({c.id}, {_args(c.name, c.technology, c.description)})")
    if model.externals:
        lines.append("")
        lines += [_external(e, "    ") for e in sorted(model.externals, key=lambda e: e.id)]
    if view.relations:
        lines.append("")
        for r in view.relations:
            lines.append(f"    Rel({r.source}, {r.target}, {_args(r.label, r.technology)})")
    return "\n".join(lines) + "\n"


__all__ = ["Container", "RenderMeta", "header", "render_c4"]
